def _published_response(schema: dict[str, Any]) -> dict[str, Any]:
    """One operation's 200 response object."""
    return {
        "description": "Successful Response",
        "content": {"application/json": {"schema": schema}},
    }


def document_responses(app: Any) -> Any:
    """Publish the derived 200 schemas on the OpenAPI document.

    Wraps whatever ``app.openapi`` currently is, so this composes with
    ``api_request_contract.document_request_bodies`` rather than replacing it -
    both mutate the one cached document in place and the later wrapper must call
    the earlier one, not FastAPI's generator.
    """
    generate = app.openapi

    def openapi() -> dict[str, Any]:
        schema = generate()
        for route in app.routes:
            if not isinstance(route, APIRoute):
                continue
            for method in route.methods:
                operation = schema["paths"].get(route.path, {}).get(method.lower())
                if operation is None:
                    continue
                published = RESPONSE_SCHEMAS.get((method, route.path))
                if published is not None:
                    operation.setdefault("responses", {})["200"] = _published_response(
                        published
                    )
                elif (method, route.path) == ("GET", "/metrics"):
                    # Not JSON at all; say what it is.
                    operation.setdefault("responses", {})["200"] = {
                        "description": "Prometheus text exposition format",
                        "content": {METRICS_CONTENT_TYPE: {"schema": {"type": "string"}}},
                    }
        app.openapi_schema = schema
        return schema

    app.openapi = openapi  # type: ignore[method-assign]
    return openapi
