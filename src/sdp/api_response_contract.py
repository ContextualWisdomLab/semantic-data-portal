"""The published 200-response contract, derived from executed responses.

``GET /openapi.json`` documented a usable 200 schema on **0 of 60** operations.
Measured at HEAD before this module, classifying every operation's 200 schema::

    54  {"type": "object", "additionalProperties": true}   (a bare ``dict``)
     4  a bare array
     1  {} (empty schema)
     1  a bare type
    --
     0  anything a client could generate a typed model from

Every handler is annotated ``-> dict[str, Any]``, which is true and tells a
consumer nothing: a buyer generating a client from the document gets
``Dict[str, Any]`` for the catalog, the evidence pack and every governed read.
The refusal contract and the request bodies were published the same way and for
the same reason (see ``api_error_contract`` and ``api_request_contract``); this
is the third and last of the three.

**These schemas are derived by executing the routes, not written by hand.** A
hand-written response schema is the exact drift this product exists to refuse -
a published claim that disagrees with the code producing it - so
``tests/test_api_response_contract.py`` fetches every documented operation and
asserts the live response validates against what is published. Regenerate with
the script recorded in that test's docstring.

Derivation rules, chosen so a published schema cannot over-claim:

* **nothing is ``required``.** A field may be absent depending on state
  (``gap_reason``, ``invalid_configuration``, ``withheld_*``, ``audit_note``),
  and marking a key required because one probe returned it would publish a
  constraint the handler does not honour.
* **every number is ``number``, never ``integer``.** JSON Schema ``number``
  accepts integers, so the superset stays true where a field is an int in one
  state and a float in another.
* **a value observed as ``null``, and an empty array's items, publish ``{}``**
  ("any") rather than ``type: null`` - which would be a claim about a type that
  simply was not observed.
* types observed across probes (anonymous, ``?user=admin``, ``?actor=admin``)
  are **unioned**; two different observed types collapse to ``{}`` rather than
  one of them being picked.
* nesting is published to depth 5; a deeper node publishes ``type: object``
  with no properties, which says "an object" and claims nothing about its keys.

What is **not** published, declared rather than left as a silent gap:

* the 20 non-GET operations. Deriving their schemas means driving mutations, and
  the validating test would then mutate catalog, ledger and graph state - the
  graph store singleton is deliberately outside ``tests/conftest.py``'s
  restoration, so a validating test for those routes would leak nodes between
  tests. Their request bodies *are* published (``api_request_contract``).
* ``GET /metrics``, which serves Prometheus text. Its content type is corrected
  here instead: the document claimed ``application/json`` with an empty schema,
  so a generated client would have tried to JSON-parse
  ``text/plain; version=0.0.4``.
"""

